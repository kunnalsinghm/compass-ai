// guardDb.js - Compass's read-only window into Guard's database.
//
// THIS is the "shared platform" integration the blueprint describes in
// section 5: Compass never re-implements usage metering, pricing, or
// RBAC - it reads Guard's existing tables directly and treats Guard as
// the single source of truth for "what happened and who is allowed to
// see it." Compass writes NOTHING here, ever - every function in this
// file is a SELECT. Its own tables (cache, routing, evaluation,
// recommendations, savings) live in Compass's own database
// (server/storage), which Guard in turn never touches.
//
// Deployment shapes, matching Guard's own:
//
//   SINGLE-TENANT, SQLite (default) - Guard and Compass are co-located
//   self-hosted processes sharing a data volume. Point GUARD_DB_PATH at
//   Guard's data/finops.db. SQLite's WAL mode (which Guard already
//   enables) supports concurrent readers safely alongside Guard's writer.
//
//   SINGLE-TENANT, Postgres (GUARD_DB_DRIVER=postgres) - GUARD_POSTGRES_URL
//   (and GUARD_POSTGRES_SCHEMA if Guard sets FINOPS_POSTGRES_SCHEMA).
//
//   MULTI-TENANT (COMPASS_MULTI_TENANT=true, mirrors Guard's
//   FINOPS_MULTI_TENANT) - Guard keeps one Postgres schema per tenant and
//   moves api_keys/users/tenants into a shared control-plane schema. Compass
//   then:
//     * resolves a key to its tenant through the control plane (findApiKey),
//     * reads every tenant-owned table through a schema-QUALIFIED name taken
//       from the ambient tenant context (tenantContext.js) - never an
//       unqualified name and never a caller-supplied string,
//     * fails closed: a query with no tenant context throws.
//   The schema name is only ever taken from control_plane.tenants.schema_name
//   (generated by Guard, never by a customer) and re-validated against a
//   strict identifier regex before it reaches SQL. Give Compass a read-only
//   Postgres role: it needs SELECT on the control plane and tenant schemas
//   and nothing else.
//
// If Guard is unreachable (wrong path, wrong URL, Guard not running yet),
// every function here throws a clear, specific error rather than
// returning empty/zeroed data that could be mistaken for "no spend yet."

const path = require("path");
const fs = require("fs");
const tenantContext = require("./tenantContext");

const MULTI_TENANT = tenantContext.multiTenant();
const DRIVER = MULTI_TENANT || process.env.GUARD_DB_DRIVER === "postgres" ? "postgres" : "sqlite";

if (MULTI_TENANT && process.env.GUARD_DB_DRIVER === "sqlite") {
  throw new Error("guardDb: multi-tenant mode requires Postgres (Guard's multi-tenant mode is Postgres-only). Unset GUARD_DB_DRIVER=sqlite.");
}

const CONTROL_PLANE_SCHEMA = String(process.env.FINOPS_CONTROL_PLANE_SCHEMA || process.env.GUARD_CONTROL_PLANE_SCHEMA || "control_plane").toLowerCase();
if (!tenantContext.SAFE_SCHEMA_RE.test(CONTROL_PLANE_SCHEMA)) {
  throw new Error(`guardDb: control plane schema must be a lowercase identifier, got '${CONTROL_PLANE_SCHEMA}'`);
}

let impl;

if (DRIVER === "sqlite") {
  const { DatabaseSync } = require("node:sqlite");
  const GUARD_DB_PATH =
    process.env.GUARD_DB_PATH || path.join(__dirname, "..", "..", "finops-mvp", "data", "finops.db");

  if (!fs.existsSync(GUARD_DB_PATH)) {
    throw new Error(
      `guardDb: Guard's SQLite database was not found at ${GUARD_DB_PATH}. ` +
        `Set GUARD_DB_PATH to the actual path of Guard's data/finops.db, or set ` +
        `GUARD_DB_DRIVER=postgres and GUARD_POSTGRES_URL if Guard runs on Postgres.`
    );
  }

  const raw = new DatabaseSync(GUARD_DB_PATH, { readOnly: true });

  impl = {
    dialect: "sqlite",
    async get(sql, params = []) {
      return raw.prepare(sql).get(...params);
    },
    async all(sql, params = []) {
      return raw.prepare(sql).all(...params);
    },
    ready: Promise.resolve(),
  };
} else {
  const { Pool, types } = require("pg");
  types.setTypeParser(20 /* int8/bigint */, (val) => parseInt(val, 10));
  const rawSchema = process.env.GUARD_POSTGRES_SCHEMA;
  const poolConfig = { connectionString: process.env.GUARD_POSTGRES_URL };
  if (rawSchema && !MULTI_TENANT) {
    if (!/^[a-z_][a-z0-9_]*$/.test(rawSchema)) {
      throw new Error(`GUARD_POSTGRES_SCHEMA must be a lowercase identifier, got '${rawSchema}'`);
    }
    poolConfig.options = `-c search_path=${rawSchema},public`;
  }
  const pool = new Pool(poolConfig);
  pool.on("error", (err) => require("./logger").error("guardDb Postgres pool: idle client error (logged, not crashing)", { error: err.message }));

  function toPositional(sql) {
    let i = 0;
    return sql.replace(/\?/g, () => `$${++i}`);
  }

  impl = {
    dialect: "postgres",
    async get(sql, params = []) {
      const result = await pool.query(toPositional(sql), params);
      return result.rows[0];
    },
    async all(sql, params = []) {
      const result = await pool.query(toPositional(sql), params);
      return result.rows;
    },
    ready: pool.query("SELECT 1").then(() => {}),
    pool,
  };
}

// ---------------------------------------------------------------------
// Table qualification. In multi-tenant mode EVERY tenant-owned table is
// addressed as "<tenant_schema>".<table>, with the schema coming from the
// ambient tenant context. In single-tenant mode names stay bare.
// ---------------------------------------------------------------------
function T(table) {
  if (!MULTI_TENANT) return table;
  const schema = tenantContext.tenantSchema(); // throws if no context at all
  if (!schema) throw new Error(`guardDb: no tenant schema in context while reading '${table}' - refusing to fall back to an unqualified table`);
  if (!tenantContext.SAFE_SCHEMA_RE.test(schema)) throw new Error(`guardDb: unsafe tenant schema '${schema}'`);
  return `"${schema}".${table}`;
}

const CP = (table) => `"${CONTROL_PLANE_SCHEMA}".${table}`;

// ---------------------------------------------------------------------
// High-level read helpers, built on the raw get/all above. Route/engine
// code should call these rather than writing ad-hoc SQL against Guard's
// schema in five different files - one place to update if Guard's schema
// ever changes column names.
// ---------------------------------------------------------------------

function sinceDaysAgoLiteral(days, dialect) {
  // Guard's own dialectSql.js isn't reachable from this package (separate
  // deployable service - see README). Same date-boundary logic, inlined
  // here in the two dialects Guard itself supports.
  const safe = Math.max(0, Math.trunc(Number(days) || 0));
  return dialect === "postgres"
    ? `TO_CHAR((NOW() AT TIME ZONE 'UTC') - INTERVAL '${safe} days', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`
    : `datetime('now', '-${safe} days')`;
}

// Compass's own shadow tests are forwarded through Guard's proxy, so Guard
// meters them as ordinary usage tagged environment='shadow-test'. That is
// evaluation spend, not production spend: counting it would inflate the
// baseline every recommendation and savings figure is measured against.
const PRODUCTION_ONLY = "(environment IS NULL OR environment <> 'shadow-test')";

// Aggregate spend by provider/model over the trailing window - the core
// input to recommend.js and savings.js's tiered economics report.
async function getSpendByModel({ days = 30 } = {}) {
  const since = sinceDaysAgoLiteral(days, impl.dialect);
  return impl.all(
    `SELECT provider, model,
            SUM(cost_usd) AS total_cost,
            SUM(input_tokens) AS input_tokens,
            SUM(output_tokens) AS output_tokens,
            COUNT(*) AS event_count
     FROM ${T("usage_events")}
     WHERE event_time >= ${since} AND ${PRODUCTION_ONLY}
     GROUP BY provider, model`
  );
}

// Same, but broken out by team too - used for team-scoped tiered
// economics and team-scoped routing policies.
async function getSpendByModelAndTeam({ days = 30 } = {}) {
  const since = sinceDaysAgoLiteral(days, impl.dialect);
  return impl.all(
    `SELECT provider, model, team,
            SUM(cost_usd) AS total_cost,
            SUM(input_tokens) AS input_tokens,
            SUM(output_tokens) AS output_tokens,
            COUNT(*) AS event_count
     FROM ${T("usage_events")}
     WHERE event_time >= ${since} AND ${PRODUCTION_ONLY}
     GROUP BY provider, model, team`
  );
}

// Production spend between two instants (ISO strings; from inclusive, to
// exclusive). `requests` counts every event, including the zero-token events
// Compass reports for cache hits, so cost-per-request reflects what a caller
// actually paid per call. `billed_requests` counts only events that reached a
// provider (tokens > 0). Shadow-test traffic is excluded: it is Compass's own
// testing spend, not the customer's workload.
async function getSpendWindow({ from, to }) {
  const row = await impl.get(
    `SELECT COALESCE(SUM(cost_usd), 0) AS cost,
            COALESCE(SUM(input_tokens), 0) AS input_tokens,
            COALESCE(SUM(output_tokens), 0) AS output_tokens,
            COUNT(*) AS requests,
            COALESCE(SUM(CASE WHEN COALESCE(input_tokens,0) + COALESCE(output_tokens,0) > 0 THEN 1 ELSE 0 END), 0) AS billed_requests
     FROM ${T("usage_events")}
     WHERE event_time >= ? AND event_time < ? AND ${PRODUCTION_ONLY}`,
    [from, to]
  );
  return {
    cost: Number(row?.cost || 0),
    input_tokens: Number(row?.input_tokens || 0),
    output_tokens: Number(row?.output_tokens || 0),
    requests: Number(row?.requests || 0),
    billed_requests: Number(row?.billed_requests || 0),
  };
}

// This calendar month's production spend for one team - what Guard's own
// budget circuit breaker compares against the team's monthly limit.
async function getTeamMonthSpend(team) {
  if (!team) return 0;
  const now = new Date();
  const start = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), 1)).toISOString();
  const end = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth() + 1, 1)).toISOString();
  const row = await impl.get(
    `SELECT COALESCE(SUM(cost_usd), 0) AS spend FROM ${T("usage_events")}
     WHERE team = ? AND event_time >= ? AND event_time < ? AND ${PRODUCTION_ONLY}`,
    [team, start, end]
  );
  return Number(row?.spend || 0);
}

// Guard's pricing catalogue overrides - read live so Guard stays the
// single source of truth for pricing (Compass's own pricing.js keeps a
// baseline catalogue copy for when Guard has no override, but overrides
// always win, matching Guard's own precedence rule).
async function getPricingOverrides() {
  return impl.all(`SELECT provider, model, input_per_1k, output_per_1k FROM ${T("pricing_overrides")}`);
}

// RBAC: validate an X-API-Key the exact same way Guard's own auth.js
// does. Compass deliberately does not maintain its own user/key store -
// one identity system for both products.
//
// Multi-tenant: api_keys lives in the shared control plane, joined to its
// tenant so the caller learns which schema to read and whether the tenant is
// allowed to authenticate at all.
async function findApiKey(keyId) {
  if (!MULTI_TENANT) return impl.get(`SELECT * FROM api_keys WHERE key_id = ?`, [keyId]);
  return impl.get(
    `SELECT api_keys.*, tenants.schema_name AS tenant_schema, tenants.status AS tenant_status,
            tenants.trial_ends_at AS tenant_trial_ends_at, tenants.suspended_reason AS tenant_suspended_reason
     FROM ${CP("api_keys")} api_keys JOIN ${CP("tenants")} tenants ON tenants.id = api_keys.tenant_id
     WHERE api_keys.key_id = ?`,
    [keyId]
  );
}

async function countKeysAndUsers() {
  if (MULTI_TENANT) {
    // No bootstrap window on a shared platform - Guard has none either.
    return { keys: 1, users: 1 };
  }
  const [keys, users] = await Promise.all([
    impl.get(`SELECT COUNT(*) AS n FROM api_keys`),
    impl.get(`SELECT COUNT(*) AS n FROM users`).catch(() => ({ n: 0 })),
  ]);
  return { keys: Number(keys?.n || 0), users: Number(users?.n || 0) };
}

// Tenants whose background work (recommendation refresh, auto-rollback) should
// run - the same set Guard's own scheduler iterates (active + trial).
async function listActiveTenants() {
  if (!MULTI_TENANT) return [{ id: null, name: "single-tenant", schema_name: null, status: "active" }];
  return impl.all(`SELECT id, name, schema_name, status FROM ${CP("tenants")} WHERE status IN ('active', 'trial') ORDER BY id`);
}

// Model allow-listing: Compass's router should never propose routing a
// request to a model the key/team isn't allowed to use - Guard would
// reject it downstream anyway, but checking here avoids a wasted round
// trip and lets the router's explanation say WHY it didn't route.
async function getModelAllowlist(scopeType, scopeValue) {
  if (!scopeValue) return [];
  return impl.all(
    `SELECT provider, model FROM ${T("model_allowlist")} WHERE scope_type = ? AND scope_value = ?`,
    [scopeType, scopeValue]
  );
}

// Active budgets for a scope, used by the router's cost-quality dial to
// know when a team/key is already close to a Guard-enforced budget
// (see router.js's budget-aware fallback behavior).
async function getBudgetsForScope(scopeType, scopeValue) {
  if (!scopeValue) return [];
  return impl.all(`SELECT * FROM ${T("budgets")} WHERE scope_type = ? AND scope_value = ?`, [scopeType, scopeValue]);
}

// Region allow-list for a scope (Guard's data-residency control). A cached
// response must not be served to a region Guard would have refused.
async function getRegionAllowlist(scopeType, scopeValue) {
  if (!scopeValue) return [];
  return impl.all(`SELECT region FROM ${T("region_allowlist")} WHERE scope_type = ? AND scope_value = ?`, [scopeType, scopeValue]).catch(() => []);
}

// Guard's flagged_test_cases: prompt/response pairs Guard flagged as worth
// reviewing (low shadow similarity, high retry rate, ...). Compass turns them
// into permanent evaluation cases (tracePipeline.js).
async function getFlaggedTestCases({ afterId = 0, limit = 200 } = {}) {
  return impl
    .all(`SELECT * FROM ${T("flagged_test_cases")} WHERE id > ? ORDER BY id ASC LIMIT ?`, [Number(afterId) || 0, Math.min(1000, Number(limit) || 200)])
    .catch((err) => {
      if (/flagged_test_cases/.test(err.message)) return []; // older Guard without the table
      throw err;
    });
}

// Tables/columns Compass depends on. Reported by /api/health so a Guard
// upgrade that renames something fails loudly instead of returning zeros.
const REQUIRED_GUARD_COLUMNS = {
  usage_events: ["event_time", "provider", "model", "team", "environment", "input_tokens", "output_tokens", "cost_usd"],
  budgets: ["scope_type", "scope_value", "monthly_limit_usd"],
  model_allowlist: ["scope_type", "scope_value", "provider", "model"],
  pricing_overrides: ["provider", "model", "input_per_1k", "output_per_1k"],
};
const REQUIRED_IDENTITY_COLUMNS = {
  api_keys: ["key_id", "role", "team", "status"],
};

async function checkTables(spec, qualify) {
  const problems = [];
  for (const [table, cols] of Object.entries(spec)) {
    try {
      await impl.get(`SELECT ${cols.join(", ")} FROM ${qualify(table)} LIMIT 1`);
    } catch (err) {
      problems.push(`${table}: ${err.message}`);
    }
  }
  return problems;
}

async function checkSchema() {
  const problems = [];
  if (MULTI_TENANT) {
    problems.push(...(await checkTables({ ...REQUIRED_IDENTITY_COLUMNS, tenants: ["id", "schema_name", "status"] }, CP)));
    // Tenant tables: check one real tenant's schema (they share one baseline).
    const tenants = await listActiveTenants().catch(() => []);
    const sample = tenants.find((t) => t.schema_name && tenantContext.SAFE_SCHEMA_RE.test(t.schema_name));
    if (sample) {
      const qualify = (t) => `"${sample.schema_name}".${t}`;
      problems.push(...(await checkTables(REQUIRED_GUARD_COLUMNS, qualify)));
    }
  } else {
    problems.push(...(await checkTables({ ...REQUIRED_IDENTITY_COLUMNS, ...REQUIRED_GUARD_COLUMNS }, (t) => t)));
  }
  return { ok: problems.length === 0, problems };
}

module.exports = {
  dialect: impl.dialect,
  MULTI_TENANT,
  CONTROL_PLANE_SCHEMA,
  checkSchema,
  PRODUCTION_ONLY,
  ready: impl.ready,
  get: impl.get,
  all: impl.all,
  T,
  getSpendByModel,
  getSpendByModelAndTeam,
  getTeamMonthSpend,
  getSpendWindow,
  getPricingOverrides,
  findApiKey,
  countKeysAndUsers,
  listActiveTenants,
  getModelAllowlist,
  getBudgetsForScope,
  getRegionAllowlist,
  getFlaggedTestCases,
};
